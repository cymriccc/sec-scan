package report

import (
	"fmt"
	"os"
	"time"

	"github.com/cymriccc/sec-scan/internal/scanner"
)

// SaveMarkdownReport exports the audit findings into a structured Markdown document.
func SaveMarkdownReport(filename string, target string, headers []scanner.HeaderCheckResult, tlsRes *scanner.TLSCheckResult, info []scanner.InfoLeakResult, probes []scanner.EndpointCheckResult, corsRes scanner.CORSResult) error {
	risk := scanner.EvaluateRisk(headers, tlsRes, info, probes, corsRes)

	content := "# 🛡️ sec-scan Security Audit Report\n\n"
	content += fmt.Sprintf("- **Target:** `%s`  \n", target)
	content += fmt.Sprintf("- **Generated:** `%s`  \n", time.Now().Format("2006-01-02 15:04:05"))
	content += fmt.Sprintf("- **Posture Score:** `%d / 100`  \n", risk.TotalScore)
	content += fmt.Sprintf("- **Security Grade:** `%s`  \n\n", risk.Grade)

	content += "---\n\n"

	// HTTP Security Headers Section
	content += "## 🔐 HTTP Security Headers\n\n"
	content += "| Header | Status | Value / Recommendation |\n"
	content += "| :--- | :--- | :--- |\n"
	for _, h := range headers {
		status := "✅ PASS"
		val := fmt.Sprintf("`%s`", h.Value)
		if !h.Found {
			status = "❌ MISSING"
			val = fmt.Sprintf("_Recommended:_ `%s`", h.Recommended)
		}
		content += fmt.Sprintf("| **%s** | %s | %s |\n", h.Header, status, val)
	}
	content += "\n"

	// SSL/TLS Section
	content += "## 📜 SSL / TLS Certificate Audit\n\n"
	if tlsRes != nil {
		status := fmt.Sprintf("VALID (%d days remaining)", tlsRes.DaysRemaining)
		if tlsRes.IsExpired {
			status = "EXPIRED"
		}
		content += fmt.Sprintf("- **Issuer:** `%s`  \n", tlsRes.Issuer)
		content += fmt.Sprintf("- **Protocol:** `%s`  \n", tlsRes.TLSVersion)
		content += fmt.Sprintf("- **Status:** `%s`  \n\n", status)
	} else {
		content += "_No TLS Certificate details recorded._\n\n"
	}

	// CORS Section
	content += "## 🌐 CORS Configuration\n\n"
	corsStatus := "✅ SECURE"
	if corsRes.IsVulnerable {
		corsStatus = fmt.Sprintf("⚠️ VULNERABLE (%s Risk)", corsRes.RiskLevel)
	}
	content += fmt.Sprintf("- **Status:** %s  \n", corsStatus)
	content += fmt.Sprintf("- **Details:** %s  \n\n", corsRes.Details)

	// Tech Disclosure Section
	content += "## 🕵️ Server Technology Disclosure\n\n"
	content += "| Header | Status | Disclosed Value |\n"
	content += "| :--- | :--- | :--- |\n"
	for _, inf := range info {
		status := "✅ HIDDEN"
		val := "_Protected_"
		if inf.Found {
			status = "⚠️ DISCLOSED"
			val = fmt.Sprintf("`%s`", inf.Value)
		}
		content += fmt.Sprintf("| **%s** | %s | %s |\n", inf.Header, status, val)
	}
	content += "\n"

	// Endpoint Probing Section
	content += "## 🎯 Sensitive Endpoint Probing\n\n"
	content += "| Path Probed | Status | HTTP Code |\n"
	content += "| :--- | :--- | :--- |\n"
	for _, ep := range probes {
		status := "✅ SAFE"
		if ep.Exposed {
			status = fmt.Sprintf("🚨 EXPOSED (%s)", ep.Severity)
		}
		content += fmt.Sprintf("| `%s` | %s | `%d` |\n", ep.Path, status, ep.StatusCode)
	}
	content += "\n---\n"
	content += "_Report automatically generated by [sec-scan](https://github.com/cymriccc/sec-scan)._\n"

	return os.WriteFile(filename, []byte(content), 0644)
}